#!/usr/bin/env python3
"""Write klayout_drc_clip.drc: the PDK's KLayout DRC deck with a clip window.

klayout_drc_stripes.py (the KLAYOUT_DRC_RUNSET) runs this deck once per
horizontal stripe of the die, so each KLayout process holds only part of the
chip. Every rule is unchanged; the edits, marked "riscv_soc_hier" in the
output, are:
  1. -rd clip=x1,y1,x2,y2 (um) restricts the default source to that window.
  2. The four layout(source.cell_obj).select(...) sources become
     source.select(...): the first form reads the whole layout and ignores the
     clip window (checked on a test layout), the second keeps it.
  3. The thread count is also read from "threads" (what OpenLane passes; the
     deck only reads "thr", so KLAYOUT_DRC_THREADS was ignored and it always
     used 4 threads).
"""
import os
import sys

PDK_DECK = ("/data/OpenLane/pdks/volare/sky130/versions/"
            "0fe599b2afb6708d281543108caf8310912f54af/sky130A/libs.tech/"
            "klayout/drc/sky130A_mr.drc")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "klayout_drc_clip.drc")


def replace(src, old, new, count):
    if src.count(old) != count:
        sys.exit(f"expected {count} x {old!r} in the PDK deck, found {src.count(old)}")
    return src.replace(old, new)


src = open(PDK_DECK).read()

src = replace(src, "  source($input, $top_cell)\n",
              "  source($input, $top_cell)\n"
              "  # riscv_soc_hier: optional clip window, -rd clip=x1,y1,x2,y2 in um\n"
              "  if $clip\n"
              "    cx1, cy1, cx2, cy2 = $clip.split(\",\").map(&:to_f)\n"
              "    @def_source = source.clip(cx1.um, cy1.um, cx2.um, cy2.um)\n"
              "  end\n", 1)

# lines 259, 266, 552, 557 of the PDK deck (551 is a commented-out copy)
lines = src.split("\n")
hits = 0
for i, line in enumerate(lines):
    if "= layout(source.cell_obj).select(" in line and not line.lstrip().startswith("#"):
        lines[i] = ("# riscv_soc_hier: source.select keeps the clip window\n"
                    + line.replace("= layout(source.cell_obj).select(", "= source.select("))
        hits += 1
if hits != 4:
    sys.exit(f"expected 4 layout(source.cell_obj).select sources, found {hits}")
src = "\n".join(lines)

src = replace(src, "if $thr\n    threads($thr)\n",
              "# riscv_soc_hier: also accept OpenLane's \"threads\"\n"
              "if $thr || $threads\n    threads(($thr || $threads).to_i)\n", 1)

header = (f"# klayout_drc_clip.drc - generated by make_drc_deck.py from\n# {PDK_DECK}\n"
          "# Same rules; edits marked riscv_soc_hier (see make_drc_deck.py).\n\n")
open(OUT, "w").write(header + src)
print(f"wrote {OUT}")
